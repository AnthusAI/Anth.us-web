"""The production Anth.us DOM: page shell, chrome, and fragment rewriting.

Why this module exists
----------------------
The port's design contract is *the production Gatsby site's own compiled
stylesheet* (`web/css/anthus-theme.css`, generated by
`bin/build-theme-css.py` from `Anth.us/src/components/layout.scss` plus the
two CSS Modules). That stylesheet is written against a specific DOM: `.layout
> header.content > ul.js-p-target`, `.wrapper > main`, `article > .heading`,
`.gatsby-image-wrapper.right`, `.index-module--postsList--d248b`, and so on.
Papyrus's Markus shell emits a different DOM (`.markus-site-masthead`,
`.markus-document`, `.markus-figure`), so none of those selectors would match.

Rather than fork Papyrus, this module replaces
`papyrus_content.markus_renderer.shell.render_page` from the publication side
-- which is exactly the seam `SiteChrome` is there to serve, just wider than
`SiteChrome`'s four fields can express. Markus still does all the *content*
rendering; this module only decides the page envelope and translates Markus's
structural class names into the ones the Anthus stylesheet targets.

Reference for every structure here is a real rendered page under
`Anth.us/public/` (a 2026-09-24 Gatsby production build).

Sentinels
---------
`markus convert` runs without `--allow-html` (a Papyrus security invariant), so
constructs that have no Markdown or Markus-directive equivalent -- `<mark>`,
inline `<svg>`, `colspan`/`rowspan` tables, and an image's authored CSS class
-- are encoded by `anthus_mdx` as private-use-area sentinels that survive
conversion as plain text, then decoded back into HTML here. The PUA code
points cannot occur in the corpus and are letter-like to the Markdown parser,
so they never disturb emphasis or table parsing.
"""

