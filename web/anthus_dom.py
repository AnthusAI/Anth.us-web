_DIMENSION_CACHE: dict[str, tuple[int, int] | None] = {}
_ASSET_ROOTS: dict[str, Path] = {}


def set_asset_roots(roots: dict[str, Path]) -> None:
    """Where to look up an image's pixel size for the aspect-ratio sizer.

    Maps a site-absolute URL prefix to the directory that holds it, e.g.
    ``{"/assets/content/": <content submodule>, "/assets/site/": web/assets/site}``.
    Source dimensions are used even though the staged copy may be downscaled:
    the aspect ratio is identical, and the sizer's ``max-width`` only matters
    below the column width.
    """
    _ASSET_ROOTS.clear()
    _ASSET_ROOTS.update(roots)
    _DIMENSION_CACHE.clear()


def _dimensions(src: str) -> tuple[int, int] | None:
    if src in _DIMENSION_CACHE:
        return _DIMENSION_CACHE[src]
    size = None
    for prefix, root in _ASSET_ROOTS.items():
        if src.startswith(prefix):
            candidate = root / src[len(prefix):]
            if candidate.is_file():
                try:
                    from PIL import Image

                    with Image.open(candidate) as image:
                        size = image.size
                except Exception:
                    size = None
            break
    _DIMENSION_CACHE[src] = size
    return size


def image_html(
    *,
    src: str,
    alt: str = "",
    class_name: str = "",
    eager: bool = False,
) -> str:
    """One image in `gatsby-plugin-image`'s "constrained" markup shape.

    Production emits, per image: a `.gatsby-image-wrapper` with the authored
    class (`right`, `full`, `centered`, …), an inner sizer div whose
    `max-width` is the source width and which holds a transparent image of the
    source's aspect ratio, then the real image absolutely filling the wrapper.
    The absolute positioning comes from the plugin's own stylesheet, which
    `bin/build-theme-css.py` folds into `web/css/anthus-theme.css`.

    What is *not* reproduced: AVIF/WebP `srcset` derivatives and the blurred
    base64 placeholder, because this build has no image-processing pipeline.
    One `<img>` at the staged (<=1600px) size is served instead. Layout is
    identical; bytes on the wire are not.
    """
    classes = ["gatsby-image-wrapper", "gatsby-image-wrapper-constrained"]
    for token in (class_name or "").split():
        if token not in classes:
            classes.append(token)
    size = _dimensions(src)
    sizer = _sizer(*size) if size else ""
    loading = "eager" if eager else "lazy"
    return (
        f'<div class="{" ".join(classes)}">{sizer}'
        f'<img src="{html.escape(src, quote=True)}" alt="{html.escape(alt, quote=True)}" '
        f'decoding="async" loading="{loading}"></div>'
    )


# --------------------------------------------------------------------------
# Papyrus ImagePipeline wrap: gatsby-plugin-image's constrained shape
# --------------------------------------------------------------------------

#: Wrapper elements the corpus authors around an ``::image{}`` (production
#: renders them verbatim, and the stylesheet keys on them: ``.center-full-image
#: {text-align:center}`` centres a caption and an inline-block image, and
#: ``.center-small-image`` is a 60% box). ``anthus_mdx`` encodes the wrapper into
#: the image's layout as ``<layout>@<key>`` because ``::image{}`` has no other
#: channel for it; the wrap hook decodes it here.
#:
#: ``p-cfi`` stands in for ``<p class="center-full-image"><div ...>``: that is
#: invalid HTML (a parser closes the ``<p>`` before the ``<div>``), but
#: production's React client render builds the ``<p>>div`` DOM, so a reader sees
#: a centred image with the ``<p>``'s bottom margin. A ``<div>`` with the same
#: class and the ``<p>`` margin is the valid static equivalent.
IMAGE_WRAPPERS: dict[str, tuple[str, str]] = {
    "p-cfi": (
        '<div class="center-full-image" style="margin:0 0 var(--space-4) 0">',
        "</div>",
    ),
    "div-cfi": ('<div class="center-full-image">', "</div>"),
    "figure-cfi": ('<figure class="center-full-image">', "</figure>"),
    "div-csi": ('<div class="center-small-image">', "</div>"),
    "float-260": (
        '<div style="float:right;width:260px;max-width:40%;margin-left:24px;'
        'margin-bottom:16px">',
        "</div>",
    ),
    "box-420": (
        '<div style="max-width:420px;margin:0 auto var(--base-line-height)">',
        "</div>",
    ),
    "box-26rem": (
        '<div style="max-width:26rem;margin:0 auto var(--base-line-height)">',
        "</div>",
    ),
    "float-300": (
        '<div style="float:right;width:300px;margin-left:20px;margin-bottom:20px">',
        "</div>",
    ),
}

#: Layouts a wrapper can accompany. ``anthus_layout_sizes`` registers every
#: ``base@wrapper`` combination with the base layout's ``sizes``.
WRAPPABLE_LAYOUTS = ("full", "center-full-image", "center-small-image", "right-aligned")


def anthus_layout_sizes(base: dict) -> dict:
    sizes = dict(base)
    for layout in WRAPPABLE_LAYOUTS:
        for key in IMAGE_WRAPPERS:
            sizes[f"{layout}@{key}"] = base[layout]
    return sizes


def _sizer(width: int, height: int) -> str:
    """gatsby-plugin-image's aspect-ratio sizer.

    The transparent SVG carries `height`/`width` attributes (not a viewBox):
    the wrapper is `display:inline-block`, so this image's intrinsic size is
    what gives it a width at all.
    """
    return (
        f'<div style="max-width:{width}px;display:block">'
        '<img alt="" role="presentation" aria-hidden="true" '
        'src="data:image/svg+xml;charset=utf-8,%3Csvg%20height=&#x27;'
        f"{height}&#x27;%20width=&#x27;{width}&#x27;%20"
        "xmlns=&#x27;http://www.w3.org/2000/svg&#x27;%20version=&#x27;1.1&#x27;"
        '%3E%3C/svg%3E" style="max-width:100%;display:block;position:static"/>'
        "</div>"
    )


def anthus_image_wrap(wrap) -> str:
    """`ImagePipeline.wrap`: Papyrus renditions inside gatsby-plugin-image's DOM.

    Production CSS absolutely positions ``.gatsby-image-wrapper img`` and takes
    the box height from the sizer ``div`` (a transparent SVG of the source's
    aspect ratio), so that element is load-bearing.
    """
    # No authored layout: gatsby-plugin-image adds no extra class (Papyrus's
    # own default layout name, `inline`, is not a production class).
    layout, _, wrapper = (wrap.request.layout and wrap.layout or "").partition("@")
    sizer = ""
    if wrap.width and wrap.height:
        shown = wrap.display_width or wrap.width
        sizer = _sizer(shown, round(wrap.height * shown / wrap.width))
    # Live emits an empty aria-hidden placeholder div (no blur-up); the fade-in
    # script hides it once the main image decodes. A real placeholder, if the
    # pipeline is ever configured with one, goes in as an <img>.
    placeholder_style = 'style="opacity:1;transition:opacity 500ms linear"'
    if wrap.placeholder:
        placeholder = (
            f'<img aria-hidden="true" data-placeholder-image="" alt="" '
            f'src="{html.escape(wrap.placeholder, quote=True)}" {placeholder_style}>'
        )
    else:
        placeholder = f'<div aria-hidden="true" data-placeholder-image="" {placeholder_style}></div>'
    markup = (
        '<div data-gatsby-image-wrapper="" '
        f'class="gatsby-image-wrapper gatsby-image-wrapper-constrained {layout}">'
        f"{sizer}{placeholder}{wrap.inner}<noscript>{wrap.inner}</noscript></div>"
    )
    caption = (wrap.request.caption or "").strip()
    if wrapper:
        opening, closing = IMAGE_WRAPPERS[wrapper]
        if caption:
            markup += (
                f'<figcaption class="image-caption"><p>{html.escape(caption)}</p>'
                "</figcaption>"
            )
        return opening + markup + closing
    if caption:
        markup += f'<p class="image-caption">{html.escape(caption)}</p>'
    return markup


def hero_image_html(*, src: str, alt: str, class_name: str) -> str:
    """A full-bleed hero image, in `gatsby-plugin-image`'s FULL_WIDTH shape.

    FULL_WIDTH differs from the constrained shape used by `image_html`: there
    is no `max-width` sizer, just a `padding-top` percentage spacer that holds
    the aspect ratio while `.hero .hero-image` sizes the box. `layout.scss`
    switches between `.hero-image-default` and `.hero-image-wide` at 941px, so
    both are emitted and CSS picks one -- same as production.
    """
    size = _dimensions(src)
    ratio = ""
    if size:
        width, height = size
        ratio = f'<div aria-hidden="true" style="padding-top:{height / width * 100}%"></div>'
    return (
        f'<div class="gatsby-image-wrapper {html.escape(class_name, quote=True)}">'
        f"{ratio}"
        f'<img src="{html.escape(src, quote=True)}" alt="{html.escape(alt, quote=True)}" '
        'decoding="async" loading="eager"></div>'
    )


