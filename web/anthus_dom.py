@dataclass(frozen=True)
class ArticleHeading:
    """The article header: eyebrow (date, tags), title, dek, byline."""

    title: str
    date: str = ""
    authors_html: str = ""
    assistants_html: str = ""
    repository: str = ""
    draft: bool = False
    tags: tuple[str, ...] = ()
    dek: str = ""

    def html(self) -> str:
        parts = []
        meta = ""
        if self.date:
            meta += f"<time>{html.escape(self.date)}</time>"
        for tag in self.tags:
            slug = (tag or "").strip().lower().replace(" ", "-")
            meta += f'<a class="pill" href="/tags/{html.escape(slug, quote=True)}/">#{html.escape(tag)}</a>'
        if meta:
            parts.append(f'<p class="heading__meta">{meta}</p>')
        parts.append(f"<h1>{html.escape(self.title)}</h1>")
        if self.dek:
            parts.append(f'<p class="heading__dek">{html.escape(self.dek)}</p>')
        if self.authors_html:
            parts.append(f'<div class="authors">{self.authors_html}</div>')
        if self.assistants_html:
            parts.append(f'<div class="assistants">{self.assistants_html}</div>')
        if self.repository:
            label = re.sub(r"^https?://(www\.)?github\.com/", "", self.repository)
            parts.append(
                '<div class="repository"><span class="byline">code and data at </span>'
                f'<a href="{html.escape(self.repository, quote=True)}" target="_blank" '
                f'rel="noopener noreferrer">{html.escape(label)}</a></div>'
            )
        heading = '<div class="heading">' + "".join(parts) + "</div>"
        if self.draft:
            # `.draft-overlay` must be the article's first child.
            heading = (
                '<div class="draft-overlay"><h1 class="draft-overlay-text">DRAFT'
                "</h1></div>" + heading
            )
        return heading


def assert_no_markus_classes(html_text: str, where: str) -> None:
    """Guard: a `markus-*` class in the output is an unstyled element.

    The Anthus stylesheet has no rule for any of them and this build does not
    ship Markus's vendored CSS, so one leaking through is a silent visual
    regression rather than a cosmetic detail.
    """
    leaked = sorted(
        set(re.findall(r'class="([^"]*(?:markus|papyrus)-[^"]*)"', html_text))
    )
    if leaked:
        raise RuntimeError(f"{where}: unstyled markus-/papyrus- classes in output: {leaked}")


_SINGLE_ELEMENT = re.compile(r"^<(\w+)\b[^>]*>.*</\1>$", re.S)


def _markdown_inline(value: str) -> str:
    """What `markdown-to-jsx` renders for a short inline author string.

    A lone element is returned as-is; anything else (text, or text mixed with
    elements) gets a wrapping ``<span>``. Verified against the reference:
    ``<a href="/ryan">Ryan Porter</a>`` stays bare, ``and the <a>..</a> GPT``
    becomes ``<span>and the <a>..</a> GPT</span>``.
    """
    text = str(value).strip()
    if _SINGLE_ELEMENT.match(text) and text.count("<a ") <= 1 and text.startswith("<a"):
        return text
    return f"<span>{text}</span>"


def _joined(entries: list[str], css: str) -> str:
    out = []
    last = len(entries) - 1
    for index, entry in enumerate(entries):
        out.append(f'<span class="{css}">{_markdown_inline(entry)}</span>')
        if index < last - 1:
            out.append(", ")
        elif index == last - 1:
            out.append(", and " if len(entries) > 2 else " and ")
    return "".join(out)


