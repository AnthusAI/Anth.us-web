#: The consent banner (Papyrus `consent_mode`) carries its own `<style>` in the page head, so these are styled.
CONSENT_BANNER_CLASSES = frozenset({"papyrus-consent", "papyrus-consent-actions", "papyrus-consent-choice"})


def assert_no_markus_classes(html_text: str, where: str) -> None:
    """Guard: a `markus-*` class in the output is an unstyled element.

    The Anthus stylesheet has no rule for any of them and this build does not
    ship Markus's vendored CSS, so one leaking through is a silent visual
    regression rather than a cosmetic detail.
    """
    leaked = sorted(
        {
            value
            for value in re.findall(r'class="([^"]*(?:markus|papyrus)-[^"]*)"', html_text)
            if not set(value.split()) <= (PAGE_ACTION_CLASSES | CONSENT_BANNER_CLASSES)
        }
    )
    if leaked:
        raise RuntimeError(f"{where}: unstyled markus-/papyrus- classes in output: {leaked}")


_SINGLE_ELEMENT = re.compile(r"^<(\w+)\b[^>]*>.*</\1>$", re.S)


def _markdown_inline(value: str) -> str:
    """What `markdown-to-jsx` renders for a short inline author string.

    A lone element is returned as-is; anything else (text, or text mixed with
    elements) gets a wrapping ``<span>``. Verified against the reference:
    ``<a href="/ryan">Ryan Porter</a>`` stays bare, ``and the <a>..</a> GPT``
    becomes ``<span>and the <a>..</a> GPT</span>``.
    """
    text = str(value).strip()
    if _SINGLE_ELEMENT.match(text) and text.count("<a ") <= 1 and text.startswith("<a"):
        return text
    return f"<span>{text}</span>"


def _joined(entries: list[str], css: str) -> str:
    out = []
    last = len(entries) - 1
    for index, entry in enumerate(entries):
        out.append(f'<span class="{css}">{_markdown_inline(entry)}</span>')
        # Some authored entries already begin with "and " ("and the Anthus GPT").
        next_has_and = index < last and entries[index + 1].lstrip().lower().startswith("and ")
        if index < last - 1:
            out.append(", ")
        elif index == last - 1:
            out.append(" " if next_has_and else (", and " if len(entries) > 2 else " and "))
    return "".join(out)


